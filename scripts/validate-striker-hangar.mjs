import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';

const manifest=JSON.parse(readFileSync('public/assets/manifest.json','utf8'));
const entry=manifest.models.xrpl_striker_landed_optimized;
assert.ok(entry,'Meshy XRPL Striker must be registered');
assert.equal(entry.src,'/assets/models/xrpl_striker_landed_optimized.glb');
assert.equal(entry.type,'model');
assert.deepEqual(entry.scenes,['boarding']);
assert.equal(entry.bytes,7337756,'source geometry must not be deployed');
assert.equal(entry.sha256,'a665158b695c3795d3e7cf13b154fdeb6df05fa03294542f09f4929870ded923');
assert.equal(manifest.models.fighter_xrpl_striker.sha256,'80cb43c0501b491ee2b4c248b11ca55b7a95aa686e50b2874c5ffbe97bf0bdc1','legacy rollback must be preserved');
const bytes=readFileSync('public'+entry.src);
assert.equal(bytes.byteLength,entry.bytes);
assert.equal(createHash('sha256').update(bytes).digest('hex'),entry.sha256,'exact original-mesh optimized review asset');
assert.equal(bytes.toString('ascii',0,4),'glTF');
assert.equal(bytes.readUInt32LE(4),2);
assert.equal(bytes.readUInt32LE(8),bytes.length);
const gltf=JSON.parse(bytes.subarray(20,20+bytes.readUInt32LE(12)).toString('utf8'));
assert.equal(gltf.buffers.length,1);
assert.equal(gltf.meshes.length,1);
assert.equal(gltf.images.length,3);
assert.ok(gltf.images.every(x=>Number.isInteger(x.bufferView)&&!x.uri));
assert.ok(gltf.buffers.every(x=>!x.uri));
assert.ok(gltf.meshes[0].primitives[0].attributes.POSITION===0);
assert.equal(gltf.accessors[0].count,106942);
assert.equal(gltf.accessors[3].count/3,187731);
const runtime=readFileSync('src/game/definitive/MeshRuntime.ts','utf8');
const scene=readFileSync('src/game/definitive/BoardingScene.ts','utf8');
assert.match(runtime,/walkthrough\?\['xrpl_striker_landed_optimized'\]:\[\]/,'new mesh only loads in walkthrough');
assert.match(scene,/if\(this\.walkthrough&&host\.striker\)/,'legacy ship unchanged outside preview');
assert.match(scene,/fighter\.traverse\(node=>\{if\(node instanceof Mesh\)node\.visible=false;\}\)/,'old render geometry hidden');
assert.match(scene,/fighter\.add\(visual\)/,'new real 3D mesh replaces old render geometry');
assert.match(scene,/getWorldPosition\(this\.hero\.position\)/,'legacy Pilot_Exit spawn kept');
console.log('striker-hangar: verified optimized Meshy 3D asset, preserved sockets, walkthrough-only branch PASS');
