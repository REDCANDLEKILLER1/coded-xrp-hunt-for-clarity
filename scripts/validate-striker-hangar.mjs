import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {build} from 'esbuild';

const manifest=JSON.parse(readFileSync('public/assets/manifest.json','utf8'));
const entry=manifest.models.xrpl_striker_landed_optimized;
assert.ok(entry,'Meshy XRPL Striker must be registered');
assert.equal(entry.src,'/assets/models/xrpl_striker_landed_optimized.glb');
assert.equal(entry.type,'model');
assert.deepEqual(entry.scenes,['boarding']);
assert.equal(entry.bytes,4004112);
assert.equal(entry.sha256,'8e7342d021d14fece961d23b92c199c61045998cee0bab51b98f731bc15c6e4e');
assert.equal(manifest.models.fighter_xrpl_striker.sha256,'80cb43c0501b491ee2b4c248b11ca55b7a95aa686e50b2874c5ffbe97bf0bdc1','legacy fighter remains original');
const bytes=readFileSync('public'+entry.src);
assert.equal(bytes.byteLength,entry.bytes);
assert.equal(createHash('sha256').update(bytes).digest('hex'),entry.sha256,'real Meshy source-derived optimized bytes');
assert.equal(bytes.toString('ascii',0,4),'glTF');
assert.equal(bytes.readUInt32LE(4),2);
assert.equal(bytes.readUInt32LE(8),bytes.length);
const gltf=JSON.parse(bytes.subarray(20,20+bytes.readUInt32LE(12)).toString('utf8'));
assert.equal(gltf.buffers.length,1);
assert.equal(gltf.meshes.length,1);
assert.equal(gltf.images.length,3);
assert.ok(gltf.images.every(x=>Number.isInteger(x.bufferView)&&!x.uri&&x.mimeType==='image/webp'),'embedded WebP textures');
assert.ok(gltf.buffers.every(x=>!x.uri),'embedded geometry');
assert.ok(gltf.extensionsRequired.includes('EXT_meshopt_compression'),'compressed geometry needs decoder');
assert.ok(gltf.extensionsRequired.includes('KHR_mesh_quantization'),'high precision vertex packing');
assert.ok(gltf.extensionsRequired.includes('EXT_texture_webp'),'WebP textures required');
assert.ok(!gltf.extensionsRequired.includes('KHR_draco_mesh_compression'),'no Draco dependency');
const primitive=gltf.meshes[0].primitives[0];
assert.equal(gltf.accessors[primitive.attributes.POSITION].count,156084,'preserve full high-detail vertex budget');
assert.equal(gltf.accessors[primitive.indices].count/3,258404,'no melt-style destructive simplification');
assert.ok(gltf.materials[0].pbrMetallicRoughness?.baseColorTexture,'PBR albedo preserved');
assert.ok(gltf.materials[0].pbrMetallicRoughness?.metallicRoughnessTexture,'PBR metallic-roughness preserved');
assert.ok(gltf.materials[0].normalTexture,'normal detail preserved');
const loader=readFileSync('src/game/definitive/ModelAssets.ts','utf8');
const runtime=readFileSync('src/game/definitive/MeshRuntime.ts','utf8');
const scene=readFileSync('src/game/definitive/BoardingScene.ts','utf8');
assert.match(loader,/setMeshoptDecoder\(MeshoptDecoder\)/,'GLTFLoader must decode real mesh data');
assert.match(runtime,/walkthrough\?\['xrpl_striker_landed_optimized'\]:\[\]/,'ship only loads in isolated review');
assert.match(scene,/if\(this\.walkthrough&&host\.striker\)/,'legacy ship unchanged outside preview');
assert.match(scene,/fighter\.traverse\(node=>\{if\(node instanceof Mesh\)node\.visible=false;\}\)/,'legacy visual mesh hidden in review');
assert.match(scene,/fighter\.add\(visual\)/,'Meshy model attached to parked fighter anchor');
assert.match(scene,/getWorldPosition\(this\.hero\.position\)/,'Pilot_Exit socket preserved');
// Cold runtime validation: decode meshopt buffer through real GLTFLoader, not just JSON metadata.
globalThis.self=globalThis;
globalThis.createImageBitmap=async()=>({width:2048,height:2048,close(){}});
const earlier=globalThis.fetch;
globalThis.fetch=async url=>new Response(String(url).includes('manifest.json')?JSON.stringify(manifest):bytes);
try{
  const bundled=await build({entryPoints:['src/game/definitive/ModelAssets.ts'],bundle:true,format:'esm',write:false,logLevel:'silent'});
  const {loadModel,disposeObject}=await import('data:text/javascript;base64,'+Buffer.from(bundled.outputFiles[0].text).toString('base64'));
  const decoded=await loadModel('xrpl_striker_landed_optimized',new AbortController().signal);
  let triangles=0,meshes=0;
  decoded.scene.traverse(node=>{if(node.isMesh){meshes++;triangles+=(node.geometry.index?.count??node.geometry.attributes.position.count)/3;}});
  assert.equal(meshes,1,'1 real visible 3D ship mesh');
  assert.equal(triangles,258404,'all detailed hull triangles decode');
  disposeObject(decoded.scene);
}finally{globalThis.fetch=earlier;}
console.log('striker-hangar: high-fidelity Meshy GLB SHA, 258404 decoded triangles, embedded PBR and socket isolation PASS');
