import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {Box3,Vector3,AnimationMixer} from 'three';
import {build} from 'esbuild';

const manifest=JSON.parse(readFileSync('public/assets/manifest.json','utf8'));
const legacy=manifest.models.xrpman;
const entry=manifest.models.xrpman_sentinel_nov08;
assert.ok(legacy.src.endsWith('/xrpman.glb'),'legacy hero must remain untouched');
assert.equal(entry.src,'/assets/models/xrpman_sentinel_nov08.glb');
assert.equal(entry.type,'model');
assert.deepEqual(entry.scenes,['boarding']);
const bytes=readFileSync('public'+entry.src);
assert.equal(bytes.length,3920284);
assert.equal(bytes.length,entry.bytes);
assert.equal(createHash('sha256').update(bytes).digest('hex'),'de9143986d77a5b9671c748f4ee16d59f5e1d33d0b95da0f372a95118ef06944');
assert.equal(entry.sha256,createHash('sha256').update(bytes).digest('hex'));
assert.ok(bytes.length<5_000_000);
assert.equal(bytes.toString('ascii',0,4),'glTF');
assert.equal(bytes.readUInt32LE(4),2);
assert.equal(bytes.readUInt32LE(8),bytes.length);
const size=bytes.readUInt32LE(12);
const doc=JSON.parse(bytes.subarray(20,20+size).toString('utf8'));
assert.equal(doc.buffers.length,1);
assert.equal(doc.meshes.length,1);
assert.equal(doc.skins.length,1);
assert.equal(doc.skins[0].joints.length,66);
assert.equal(doc.images.length,3);
assert.deepEqual(doc.animations.map(a=>a.name),['Running','Walking','Idle']);
assert.ok(doc.images.every(image=>Number.isInteger(image.bufferView)&&!image.uri));
assert.ok(doc.buffers.every(buffer=>!buffer.uri));
const source=readFileSync('src/game/definitive/MeshRuntime.ts','utf8');
const game=readFileSync('src/game/definitive/BoardingScene.ts','utf8');
assert.match(source,/walkthrough \? 'xrpman_sentinel_nov08' : 'xrpman'/,'corrected model only in walkthrough');
assert.match(game,/this\.play\(walking\?'Running':'Idle'\)/,'actual running and idle animations');
assert.match(game,/this\.hero\.scale\.setScalar\(1\.9304\/1\.70\)/,'adjust native Meshy scale');
assert.ok(!game.includes("this.play(walking?'Walk':'Idle')"),'old walk clip not selected for new hero');

globalThis.self=globalThis;
globalThis.createImageBitmap=async()=>({width:1024,height:1024,close(){}});
const priorFetch=globalThis.fetch;
globalThis.fetch=async input=>new Response(String(input).includes('manifest.json')?JSON.stringify(manifest):bytes);
try{
  const bundled=await build({entryPoints:['src/game/definitive/ModelAssets.ts'],bundle:true,format:'esm',write:false,logLevel:'silent'});
  const {loadModel,disposeObject}=await import('data:text/javascript;base64,'+Buffer.from(bundled.outputFiles[0].text).toString('base64'));
  const gltf=await loadModel('xrpman_sentinel_nov08',new AbortController().signal);
  assert.deepEqual(gltf.animations.map(a=>a.name),['Running','Walking','Idle']);
  let skinned=0;
  gltf.scene.traverse(node=>{if(node.isSkinnedMesh)skinned++;});
  assert.equal(skinned,1);
  gltf.scene.scale.setScalar(1.9304/1.7);
  const height=new Box3().setFromObject(gltf.scene).getSize(new Vector3()).y;
  assert.ok(height>1.65&&height<2.35,'character is in human-scale bounds: '+height);
  const mixer=new AnimationMixer(gltf.scene);
  const run=gltf.animations.find(a=>a.name==='Running');
  const idle=gltf.animations.find(a=>a.name==='Idle');
  assert.ok(run.duration>.5&&run.duration<2,'real running animation cycle');
  assert.ok(idle.duration>.8&&idle.duration<1.2,'valid standing pose duration');
  const hips=gltf.scene.getObjectByName('mixamorig:Hips');
  assert.ok(hips,'Mixamo hips must resolve');
  mixer.clipAction(run).play();
  mixer.update(.2);
  const first=hips.position.clone();
  mixer.update(.23);
  assert.ok(first.distanceTo(hips.position)>.002,'running hip animation must actually move');
  mixer.stopAllAction();mixer.clipAction(idle).reset().play();
  mixer.update(.1);const pose=hips.position.clone();
  mixer.update(.6);assert.ok(pose.distanceTo(hips.position)<.0001,'idle remains stationary');
  disposeObject(gltf.scene);
}catch(error){throw error;}
finally{globalThis.fetch=priorFetch;}
console.log('sentinel-nov08: model SHA, 66 joints, 1K embedded maps, real Run/Idle playback and legacy preservation PASS');
