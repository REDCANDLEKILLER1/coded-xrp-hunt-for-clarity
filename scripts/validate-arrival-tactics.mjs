import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {build} from 'esbuild';

const compiled=await build({entryPoints:['src/game/definitive/ArrivalTacticsRules.ts'],bundle:true,platform:'node',format:'esm',write:false,logLevel:'silent'});
const rules=await import('data:text/javascript;base64,'+Buffer.from(compiled.outputFiles[0].text).toString('base64'));
const {ACTION_POINTS,MOVE_RANGE_METRES,createTacticalActor,gainTacticalXp,canTacticalMove,tacticalDamage,pinchTacticalCamera}=rules;
assert.equal(ACTION_POINTS,2);
assert.equal(MOVE_RANGE_METRES,6);
const hero=createTacticalActor('xrpman',100,22);
const guard=createTacticalActor('security_guard',60,11);
assert.equal(hero.level,1);
assert.equal(guard.level,1);
assert.equal(hero.xp,0);
assert.equal(gainTacticalXp(hero,60).level,2,'first guard grants a meaningful Level 2 demonstration');
assert.equal(gainTacticalXp(hero,60).xp,10,'excess XP carries forward');
assert.equal(gainTacticalXp(hero,60).attack,25,'individual actors gain attack strength');
assert.equal(guard.level,1,'XP for hero does not change the guard');
assert.equal(hero.level,1,'input actor immutable');
assert.equal(gainTacticalXp(guard,60).level,2,'per-actor upgrade works for any actor');
assert.equal(tacticalDamage(11,false),11);
assert.equal(tacticalDamage(11,true),5,'cover reduces incoming damage');
assert.equal(canTacticalMove({x:0,z:0},{x:0,z:6},1),true);
assert.equal(canTacticalMove({x:0,z:0},{x:0,z:6.1},1),false);
assert.equal(canTacticalMove({x:0,z:0},{x:0,z:6},0),false);
assert.equal(canTacticalMove({x:0,z:0},{x:14,z:0},2),false);
assert.equal(pinchTacticalCamera(1,100,200),.62,'pinch in clamp');
assert.equal(pinchTacticalCamera(1,200,100),1.65,'pinch out clamp');
assert.equal(pinchTacticalCamera(1,0,100),1,'invalid pinch ignored');

const main=readFileSync('src/main.ts','utf8');
const mesh=readFileSync('src/game/definitive/MeshRuntime.ts','utf8');
const scene=readFileSync('src/game/definitive/ArrivalTacticsScene.ts','utf8');
assert.ok(main.includes("params.get('review') === 'tactics'"),'direct isolated review route');
assert.ok(main.includes('meshRuntime.showArrivalTactics()'),'route launches tactical review');
assert.ok(mesh.includes('async showArrivalTactics()'),'Three.js scene entrypoint');
assert.ok(mesh.includes("loadModel('xrpman',signal)"),'existing verified character asset in prototype');
assert.ok(scene.includes("private phase:TacticalPhase='explore'"),'starts free exploration');
assert.ok(scene.includes("this.phase='player'"),'enemy contact enters turn-based combat');
assert.ok(scene.includes('this.actor=gainTacticalXp(this.actor,60)'),'victory progression');
assert.ok(scene.includes("this.ap=ACTION_POINTS"),'turn action points');
assert.ok(scene.includes('this.coverPositions'),'real cover positions');
assert.ok(scene.includes('this.touches.size>=2'),'mobile pinch input');
assert.ok(!scene.includes('save.update(')&&!scene.includes('save.claim('),'prototype must not mutate campaign progression');
console.log('arrival-tactics: OK');
