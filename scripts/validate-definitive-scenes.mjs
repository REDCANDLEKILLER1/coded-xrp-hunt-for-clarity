import assert from 'node:assert/strict';
import { build } from 'esbuild';
const compiled = await build({ entryPoints: ['src/game/definitive/SceneController.ts'], bundle: true, format: 'esm', write: false, logLevel: 'silent' });
const { SceneController } = await import(`data:text/javascript;base64,${Buffer.from(compiled.outputFiles[0].text).toString('base64')}`);
const controller = new SceneController();
const active = new Set();
function scene(name) {
  const log = { disposed: 0, updates: [], renders: 0 };
  return { log, setActive(value) { if (value) active.add(name); else active.delete(name); assert.ok(active.size <= 1, 'at most one scene can own input'); }, update(dt) { log.updates.push(dt); }, render() { log.renders++; }, dispose() { active.delete(name); log.disposed++; } };
}
const earth = scene('earth');
assert.equal(await controller.change(async () => earth), true);
controller.frame(4);
assert.equal(earth.log.updates[0], .05, 'background time cannot advance a whole combat frame');
let finishOld;
let oldSignal;
const stale = scene('stale');
const first = controller.change((signal) => { oldSignal = signal; return new Promise((resolve) => { finishOld = resolve; }); });
controller.frame(.016);
assert.equal(earth.log.updates.length, 1, 'loading pauses simulation');
assert.equal(active.size, 0, 'loading releases input');
const boarding = scene('boarding');
assert.equal(await controller.change(async () => boarding), true);
assert.equal(oldSignal.aborted, true);
finishOld(stale);
assert.equal(await first, false, 'stale loader cannot replace the chosen scene');
assert.equal(stale.log.disposed, 1);
assert.equal(earth.log.disposed, 1);
assert.deepEqual([...active], ['boarding']);
assert.equal(await controller.change(async () => { throw new Error('asset download failed'); }), false);
assert.deepEqual([...active], ['boarding'], 'failed load restores the prior scene input');
assert.equal(controller.lastError, 'asset download failed');
controller.frame(.02);
assert.deepEqual(boarding.log.updates, [.02]);
let finishAfterClose;
const pending = controller.change(() => new Promise((resolve) => { finishAfterClose = resolve; }));
controller.clear();
finishAfterClose(stale);
assert.equal(await pending, false);
assert.equal(boarding.log.disposed, 1);
assert.equal(active.size, 0);
controller.clear();
assert.equal(boarding.log.disposed, 1, 'repeated exit is idempotent');
console.log('definitive-scenes: OK — one input owner, paused loads, stale load cancellation/disposal, recovery after errors, idempotent exit.');
