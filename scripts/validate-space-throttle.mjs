import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {build} from 'esbuild';
const result=await build({entryPoints:['src/game/definitive/SpaceThrottle.ts'],bundle:true,write:false,format:'esm',logLevel:'silent'});
const throttle=await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
assert.equal(throttle.stepThrottle(1,1),1.1);
assert.equal(throttle.stepThrottle(1,-1),.9);
assert.equal(throttle.stepThrottle(2.2,1),2.2,'upper throttle stop');
assert.equal(throttle.stepThrottle(.25,-1),.25,'lower throttle stop');
assert.equal(throttle.commandedSpeed(130,1,false,false),130);
assert.equal(throttle.commandedSpeed(130,.5,false,false),65);
assert.equal(throttle.commandedSpeed(130,.5,true,false),32.5,'brake temporarily overrides throttle');
assert.equal(throttle.commandedSpeed(130,.5,false,true),286,'boost temporarily overrides throttle');
const scene=readFileSync('src/game/definitive/SpaceScene.ts','utf8');
assert.match(scene,/addEventListener\('wheel'.*changeThrottle/s,'desktop wheel controls the throttle');
assert.match(scene,/data-throttle=readout/,'touch throttle has a live readout');
assert.doesNotMatch(scene,/addEventListener\('blur',this\.pause/,'ordinary focus loss must not force a pause');
assert.match(scene,/visibilitychange.*this\.pause/s,'actually hiding the game still pauses safely');
console.log('space-throttle: OK — bounded wheel/touch throttle drives commanded speed; boost and brake override it; focus loss clears controls without pausing.');
